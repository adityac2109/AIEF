"""Generate summary tables and figures for a detect run.

Usage:
    python -m bearingguard.reporting.report runs/protocol_v1_dev --out docs/results/protocol_v1_dev

Writes <out>/summary.md and <out>/figures/*.png. Every number and plot comes
from the run directory and the cached feature files it recorded.
"""

from __future__ import annotations

import argparse
import json
import tomllib
from pathlib import Path

import pandas as pd

from bearingguard.config import get_data_dir
from bearingguard.data.ims import get_spec
from bearingguard.experiments.detect import load_test
from bearingguard.reporting import figures, tables


def build_report(run_dir: Path, out: Path, data_dir: Path) -> Path:
    cfg = tomllib.loads((run_dir / "config.toml").read_text())
    meta = json.loads((run_dir / "metadata.json").read_text())
    allow_sealed = bool(meta.get("allow_sealed", False))
    per_bearing = pd.read_csv(run_dir / "per_bearing.csv")
    validity = pd.read_csv(run_dir / "validity.csv")
    timeline = pd.read_csv(run_dir / "timeline.csv", parse_dates=["timestamp"])
    methods = [m["name"] for m in cfg["methods"]]
    grid, ifc = cfg["grid"], cfg["isolation_forest"]

    fig_dir = out / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    feats, failures = {}, {}
    for t in cfg["tests"]:
        feats[t] = load_test(data_dir, t, cfg, allow_sealed)
        failures[t] = get_spec(t, allow_sealed=allow_sealed).failures
        figures.alarm_raster(timeline, feats[t], t, failures[t], methods,
                             fig_dir / f"alarm_raster_test{t}.png", cfg["max_operating_gap_s"])
    figures.tradeoff(per_bearing, methods, ifc["primary_seed"], fig_dir / "tradeoff.png")
    if not validity.empty:
        figures.validity(validity, methods, ifc["primary_seed"], fig_dir / "validity.png")
    if all("env_bpfo" in f.columns for f in feats.values()):
        figures.envelope_failed(feats, failures, fig_dir / "envelope_failed.png",
                                cfg["max_operating_gap_s"])

    md = tables.to_markdown
    failed_order = (per_bearing[per_bearing["failed"]][["test_id", "bearing"]]
                    .drop_duplicates().sort_values(["test_id", "bearing"]).itertuples(index=False))
    parts = [
        f"# Results: `{cfg['name']}`",
        "Generated by `python -m bearingguard.reporting.report`. Do not edit by hand.",
        f"Run commit `{meta['git_commit'][:7]}` (tree clean: {not meta['git_dirty']}), "
        f"tests {cfg['tests']}, sealed data allowed: {allow_sealed}, runtime {meta['total_runtime_s']} s.",
        f"## Primary settings (k = {grid['primary_k']:g}, α = {grid['primary_alpha']:g}, "
        f"Isolation Forest seed {ifc['primary_seed']})",
        "Lead times and early-half episodes are listed per failed bearing in the order "
        + " / ".join(f"T{t}B{b}" for t, b in failed_order) + ".",
        md(tables.primary_table(per_bearing)),
        "## Per bearing (primary settings)",
        "Failed bearings: D = detected (in alarm within the final window) or -, first-alarm lead time, "
        "episodes, time in alarm. Non-failed: episodes, time in alarm.",
        md(tables.per_bearing_table(per_bearing)),
        "## Threshold sensitivity (primary seed)",
        md(tables.sensitivity_table(per_bearing, ifc["primary_seed"])),
        f"## Isolation Forest seed variation ({len(ifc['seeds'])} seeds, primary threshold)",
        md(tables.seed_table(per_bearing, grid["primary_k"], grid["primary_alpha"])),
    ]
    if not validity.empty:
        parts += ["## Calibration p-value: observed vs nominal exceedance (non-failed bearings, primary seed)",
                  md(tables.validity_table(validity, ifc["primary_seed"]))]
    parts += ["## Figures"] + [f"![{p.stem}](figures/{p.name})" for p in sorted(fig_dir.glob("*.png"))]
    (out / "summary.md").write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    return out / "summary.md"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("run_dir", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--data-dir", help="overrides BEARINGGUARD_DATA_DIR")
    args = parser.parse_args(argv)
    path = build_report(args.run_dir, args.out, get_data_dir(args.data_dir))
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
